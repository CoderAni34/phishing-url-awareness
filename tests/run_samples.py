"""Run all five workbook examples; optionally refresh the evidence table."""

import argparse
from datetime import date
from pathlib import Path
import platform

from tests.samples import SAMPLES
from url_checker.rules import inspect_url


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh tests/test_samples.md")
    args = parser.parse_args()
    rows = []
    failures = 0
    for number, (url, expected) in enumerate(SAMPLES, 1):
        actual = inspect_url(url)
        status = "PASS" if actual == expected else "FAIL"
        failures += status == "FAIL"
        print(f"{number}. {url}")
        for message in actual:
            print("   - " + message)
        print("   " + status)
        rows.append(f"| {number} | `{url}` | {'<br>'.join(expected)} | {'<br>'.join(actual)} | {status} |")
    print(f"\n{len(SAMPLES) - failures}/{len(SAMPLES)} workbook samples passed.")
    if args.write:
        report = (
            "# Test Results\n\n"
            f"Python version used: {platform.python_version()} | Operating system: {platform.system()} "
            f"{platform.release()} | Date: {date.today().isoformat()}\n\n"
            "Actual results below were generated by calling the real checker locally, not copied from expectations.\n"
            "Reproduce: `python -B -m tests.run_samples --write`\n\n"
            "| # | Input | Expected result | Actual result | Pass/Fail |\n"
            "|---|-------|-----------------|---------------|-----------|\n"
            + "\n".join(rows)
            + "\n\n## Notes\n\n"
            "These examples demonstrate that a URL with no listed signs is not proven safe.\n"
            "The @ sample demonstrates why the hostname after user information matters.\n"
            "The five required examples do not exercise the length rule; automated tests cover its 100/101 boundary.\n"
            "These are generated observations, not a claim of the student's personal learning experience.\n"
        )
        Path(__file__).with_name("test_samples.md").write_text(report, encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
